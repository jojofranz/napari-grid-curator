    def _detect_and_create_channels_from_dataset(self):
        """
        Detect all unique channels in the dataset and create dynamic Channels enum.
        
        Scans all scenes to find which channels exist in the DataFrames,
        then creates a dynamic Channels enum with those channel names.
        This makes the plugin truly data-agnostic.
        
        Returns:
            tuple: (Channels enum, list of channel enum members)
        """
        if self.dataset is None or not self.scene_choices:
            print("WARNING: No dataset loaded, cannot detect channels")
            return None, []
        
        # Collect all unique channel names from all scenes
        all_channels = set()
        for scene_name in self.scene_choices:
            df = self.dataset[scene_name]['df']
            if 'channel' in df.columns:
                all_channels.update(df['channel'].unique())
        
        # Sort for consistent ordering
        channel_names = sorted(all_channels)
        
        print(f"\n=== Detected {len(channel_names)} channels in dataset ===")
        print(f"  {', '.join(channel_names)}")
        print("=========================================\n")
        
        # Create dynamic Channels enum
        if channel_names:
            self.Channels = create_channels_enum(channel_names)
            # Create list of all channel enum members
            channel_members = [self.Channels[name] for name in channel_names]
            return self.Channels, channel_members
        else:
            print("WARNING: No channels found in dataset!")
            return None, []
    
