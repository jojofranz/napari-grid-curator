    def change_viewing_mode(self, mode_str):
        """
        Handle viewing mode change.
        
        Parameters:
            mode_str: 'mosaic' or 'slide'
        """
        self.viewing_mode = ViewingMode[mode_str]
        
        if self.viewing_mode == ViewingMode.slide:
            self.slide_nav_container.show()
            # Hide batch controls in slide mode
            self.select_batch_widget._widget._qwidget.hide()
        else:
            self.slide_nav_container.hide()
            self.select_batch_widget._widget._qwidget.show()
            # Remove slide mode layers when switching back to mosaic
            layers_to_remove = ['slide_image', 'slide_labels']
            for layer_name in layers_to_remove:
                if layer_name in self.viewer.layers:
                    self.viewer.layers.remove(layer_name)
        
        # Reload current scene with new mode
        if self.has_initialized_scene and self.current_scene is not None:
            self.load_scene(self.current_scene)
            
            # Reset camera view when switching to mosaic
            if self.viewing_mode == ViewingMode.mosaic:
                self.viewer.reset_view()
    
    def prev_cell_slide_mode(self):
        """Navigate to previous cell in slide mode."""
        if self.slide_mode_cell_index > 0:
            self.slide_mode_cell_index -= 1
            self._update_slide_mode_display()
    
    def next_cell_slide_mode(self):
        """Navigate to next cell in slide mode."""
        if self.slide_mode_cell_index < len(self.slide_mode_cells) - 1:
            self.slide_mode_cell_index += 1
            self._update_slide_mode_display()
    
    def goto_cell_slide_mode(self, cell_num):
        """Navigate to specific cell number in slide mode.
        
        Parameters:
            cell_num (int): 1-indexed cell number to navigate to
        """
        cell_num = int(cell_num)
        if 1 <= cell_num <= len(self.slide_mode_cells):
            self.slide_mode_cell_index = cell_num - 1
            self._update_slide_mode_display()
        else:
            print(f"Cell number {cell_num} out of range (1-{len(self.slide_mode_cells)})")
    
    def _update_slide_mode_display(self):
        """Update the display in slide mode for current cell."""
        if not self.slide_mode_cells:
            return
        
        # Update label and spinbox
        self.current_cell_label.setText(f"Cell: {self.slide_mode_cell_index + 1}/{len(self.slide_mode_cells)}")
        self.goto_cell_spinbox.value = self.slide_mode_cell_index + 1
        
        # Get current cell info
        cell_row = self.slide_mode_cells[self.slide_mode_cell_index]
        label = cell_row['label']
        
        # Center view on the cell
        bbox = [int(cell_row['bbox-0']), int(cell_row['bbox-2']), 
               int(cell_row['bbox-1']), int(cell_row['bbox-3'])]
        center_y = (bbox[0] + bbox[1]) / 2
        center_x = (bbox[2] + bbox[3]) / 2
        
        # Update viewer camera to center on cell
        self.viewer.camera.center = (0, center_y, center_x)
        self.viewer.camera.zoom = 2.0  # Zoom in on the cell
        
        # Update info display
        print(f"Slide mode: Showing cell {label} at ({center_y:.0f}, {center_x:.0f})")

