    def get_create_layer(self, viewer, data, name, visible=True, translate=None, layer_type='image', 
                         features=None, text=None, face_color=None, face_color_cycle=None):
        """
        Get existing napari layer or create new one with specified properties.
        
        This helper method manages layer lifecycle: if a layer with the given
        name exists, it updates its data; otherwise it creates a new layer.
        
        Parameters:
            viewer (napari.Viewer): Napari viewer instance
            data (np.ndarray): Layer data (image, labels, or coordinates)
            name (str): Layer name (used for identification)
            visible (bool): Whether layer should be visible (default: True)
            translate (tuple): (y, x) translation offset (default: None)
            layer_type (str): Type of layer - 'image', 'labels', or 'points'
            features (dict): Point features for text/color mapping (points only)
            text (dict): Text display configuration (points only)
            face_color (array): Point colors (points only)
            face_color_cycle (array): Unused (kept for compatibility)
            
        Returns:
            napari.layers.Layer: The updated or newly created layer
            
        Layer Type Specifics:
            - 'image': Multi-channel image data, typically (H, W, C)
            - 'labels': Integer labels for segmentation masks
            - 'points': Coordinates with optional features and text overlays
            
        TODO: Maybe replace points by shapes? Then shapes could serve a test-backgrounds. Currently some text-colors are not very visible against the image
        """
        for layer in viewer.layers:
            if layer.name == name:
                layer.data = data
                layer.visible = visible
                layer.translate = translate
                if layer_type == 'image':
                    self._set_scalar_image_contrast_limits(layer, data)
                if layer_type == 'points':
                    if features is not None:
                        layer.features = features
                    else:
                        layer.features = None
                    if text is not None:
                        layer.text = text
                    else:
                        layer.text = None
                    if face_color is not None:
                        layer.face_color = face_color
                    else:
                        layer.face_color = 'white'
                return layer

        if layer_type == 'image':
            layer = viewer.add_image(data, name=name, visible=visible, translate=translate)
            self._set_scalar_image_contrast_limits(layer, data)
        elif layer_type == 'labels':
            viewer.add_labels(data, name=name, visible=visible, translate=translate)
        elif layer_type == 'points':
            if np.any([features is None, text is None, face_color is None]):
                viewer.add_points(data, name=name, visible=visible, translate=translate, border_width=0, features=features)
            else:
                viewer.add_points(data, name=name, visible=visible, translate=translate, border_width=0, features=features, text=text, face_color=face_color)

    def _set_scalar_image_contrast_limits(self, layer, data):
        """Set contrast limits for scalar microscopy images without touching RGB(A)."""
        data = np.asarray(data)
        is_rgb_like = data.ndim >= 3 and data.shape[-1] in (3, 4)
        if is_rgb_like or data.size == 0:
            return

        finite = data[np.isfinite(data)]
        if finite.size == 0:
            return

        low = float(np.min(finite))
        high = float(np.max(finite))
        if high > low:
            layer.contrast_limits = (low, high)



