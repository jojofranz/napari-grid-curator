    def save_dataset(self):
        """
        Save complete dataset with all changes.
        
        Handles all three dataset formats:
        - Legacy: Saves all-in-one .pkl
        - Lazy: Updates main .pkl and per-scene image files
        - Minimal: Updates main .pkl only (images/labels unchanged)
        
        Saves:
        1. Updated .pkl file with modified exclusion/positivity data
        2. CSV file with all measurements
        3. Excel summary file with cell count combinations
        
        File naming:
            Automatically increments version number (e.g., dataset_v1.pkl,
            dataset_v2.pkl) to prevent overwriting previous saves.
            
        Side Effects:
            - Updates dataset file selector to point to new file
            - Shows info notification with save location
        """
        new_file_path = get_new_file_path(self.input_file_path)

        for _ in progress(range(1)):
            if self.dataset_mode == 'legacy':
                # Save entire dataset as before
                with open(new_file_path, 'wb') as f:
                    pickle.dump(self.dataset, f)
            
            elif self.dataset_mode == 'lazy':
                # Save metadata + DataFrames, update image files if needed               
                # Create same structure as pickle_dataset_for_napari_lazy
                images_dir = os.path.join(os.path.dirname(new_file_path), 'napari_images')
                os.makedirs(images_dir, exist_ok=True)
                
                image_files = {}
                for scene_name in self.scene_choices:
                    # Copy or update image files (images don't change in plugin)
                    safe_name = scene_name.replace('/', '_').replace('\\', '_').replace(' ', '_')
                    new_img_file = os.path.join(images_dir, f'{safe_name}_images.pkl')
                    
                    # If images are loaded, save them; otherwise copy old file
                    if self.dataset[scene_name]['images'] is not None:
                        with open(new_img_file, 'wb') as f:
                            pickle.dump(self.dataset[scene_name]['images'], f)
                    else:
                        # Copy from original location
                        import shutil
                        old_img_file = os.path.join(self.dataset_loader.base_dir, 
                                                    self.dataset[scene_name]['_image_file'])
                        if os.path.exists(old_img_file):
                            shutil.copy2(old_img_file, new_img_file)
                    
                    image_files[scene_name] = os.path.relpath(new_img_file, os.path.dirname(new_file_path))
                
                # Save main file
                data = {
                    'format_version': 'lazy_v1',
                    'scene_names': self.scene_choices,
                    'dataframes': {scene: self.dataset[scene]['df'] for scene in self.scene_choices},
                    'image_files': image_files,
                    'base_dir': os.path.dirname(new_file_path)
                }
                with open(new_file_path, 'wb') as f:
                    pickle.dump(data, f)
            
            elif self.dataset_mode == 'minimal':
                # Only save DataFrames and metadata (images/labels unchanged)
                # Handle both 2D (.lif-based) and 3D (file-based) minimal formats
                data = {
                    'format_version': 'minimal_v1',
                    'save_format': self.dataset_loader.metadata['save_format'],
                    'scene_names': self.scene_choices,
                    'dataframes': {scene: self.dataset[scene]['df'] for scene in self.scene_choices},
                    'label_files': {scene: self.dataset[scene]['_label_file'] for scene in self.scene_choices},
                    'base_dir': os.path.dirname(new_file_path),
                }
                
                # Add format-specific metadata
                if hasattr(self.dataset_loader, '_is_3d_file_based') and self.dataset_loader._is_3d_file_based:
                    # 3D file-based minimal format
                    data['image_file'] = self.dataset_loader.metadata['image_file']
                    data['image_filetype'] = self.dataset_loader.metadata['image_filetype']
                    data['image_dims'] = self.dataset_loader.metadata['image_dims']
                    data['segmentation_filetype'] = self.dataset_loader.metadata['segmentation_filetype']
                    data['segmentation_dims'] = self.dataset_loader.metadata['segmentation_dims']
                    data['relabel'] = self.dataset_loader.metadata.get('relabel', False)
                    data['channel_names'] = self.dataset_loader.metadata.get('channel_names', [])
                    data['ndim'] = 3
                else:
                    # 2D .lif-based minimal format
                    data['lif_file'] = self.dataset_loader.metadata['lif_file']
                    data['emission_to_fluorophore_map'] = self.dataset_loader.metadata.get('emission_to_fluorophore_map', {})
                    data['cmaps'] = self.dataset_loader.metadata.get('cmaps', {})
                
                with open(new_file_path, 'wb') as f:
                    pickle.dump(data, f)


        new_file_path_csv = new_file_path.replace('.pkl', '.xlsx')
        # self.write_spreadsheets(new_file_path_csv)
        self.write_summary(new_file_path_csv.replace('.xlsx', '_summary.xlsx'))

        show_info(f"INFO: Saved dataset to {new_file_path}")

        # Re-load
        # self.select_dataset_widget.value = new_file_path


