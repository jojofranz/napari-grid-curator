        @self.viewer.mouse_drag_callbacks.append
        def update_partition(layer, event):

            if 'Alt' in event.modifiers and self.has_initialized_scene:
                print('\n=== Alt-Click (Tile-Based) Debug ===')
                print(f'Event position: {event.position}')
                
                try:
                    # Determine which label layer to use based on viewing mode
                    viewing_mode = getattr(self, 'viewing_mode', ViewingMode.mosaic)
                    if viewing_mode == ViewingMode.slide:
                        if 'slide_labels' not in self.viewer.layers:
                            print("Slide labels layer not found")
                            return
                        labels_data = self.viewer.layers['slide_labels'].data
                    else:
                        if 'all_labels' not in self.viewer.layers:
                            print("All labels layer not found")
                            return
                        labels_data = self.viewer.layers['all_labels'].data
                    
                    # Get click position
                    position = np.round(event.position).astype(int)
                    print(f'Position (rounded): {position}')
                    
                    
                    # Determine if 2D or 3D based on all_labels shape
                    is_3d = labels_data.ndim == 3
                    
                    # Extract Y, X coordinates (works for both 2D and 3D)
                    if is_3d:
                        z_idx, y_idx, x_idx = position[0], position[1], position[2]
                    else:
                        y_idx, x_idx = position[0], position[1]

                    # Slide mode: direct label lookup, no tile/image updates
                    if viewing_mode == ViewingMode.slide:
                        if is_3d:
                            clicked_label = labels_data[z_idx, y_idx, x_idx]
                        else:
                            clicked_label = labels_data[y_idx, x_idx]

                        if clicked_label == 0:
                            print('No label at clicked position (background)')
                        else:
                            df_scene = self.dataset[self.current_scene]['df']
                            label_mask = df_scene['label'] == clicked_label
                            if not np.any(label_mask):
                                print(f'Clicked label {clicked_label} not found in DataFrame')
                                return

                            current_exclude = df_scene.loc[label_mask, 'exclude'].iloc[0]
                            new_exclude = not current_exclude
                            df_scene.loc[label_mask, 'exclude'] = new_exclude
                            print(f'Toggled label {clicked_label} exclude: {current_exclude} -> {new_exclude}')
                            print('Slide mode: exclusion updated in DataFrame only (no included/excluded tile columns).')
                            # TODO(slide-mode): add visual feedback for include/exclude status.
                        return
                    
                    # Check if in excluded region
                    in_excluded = x_idx >= self.excluded_translate[1]
                    if in_excluded:
                        x_idx = x_idx - int(self.excluded_translate[1])
                        print(f'Click in excluded region, adjusted x: {x_idx}')
                    
                    # Calculate which tile was clicked using grid layout
                    if hasattr(self, 'current_batch_labels') and len(self.current_batch_labels) > 0:
                        # Get actual tile dimensions (accounts for montage mode)
                        tile_h = getattr(self, 'current_tile_h', self.crop_size)
                        tile_w = getattr(self, 'current_tile_w', self.crop_size)
                        padding = 5
                        
                        print(f'Tile size: {tile_h}x{tile_w}, padding: {padding}')
                        
                        # Calculate which tile row and column
                        row = y_idx // (tile_h + padding)
                        col = x_idx // (tile_w + padding)
                        
                        print(f'Clicked tile: row={row}, col={col}')
                        
                        # Check if click is in padding
                        y_in_tile = y_idx % (tile_h + padding)
                        x_in_tile = x_idx % (tile_w + padding)
                        
                        if y_in_tile >= tile_h or x_in_tile >= tile_w:
                            print('Click in padding, ignoring')
                        else:
                            # Calculate linear index
                            tile_idx = row * self.n_cols + col
                            
                            if tile_idx < len(self.current_batch_labels):
                                selected_label = self.current_batch_labels[tile_idx]
                                print(f'Selected label from tile index {tile_idx}: {selected_label}')
                                
                                # Toggle exclude status
                                current_exclude = self.dataset[self.current_scene]['df'].loc[
                                    self.dataset[self.current_scene]['df']['label'] == selected_label, 'exclude'
                                ].values[0]
                                
                                new_exclude = not current_exclude
                                self.dataset[self.current_scene]['df'].loc[
                                    self.dataset[self.current_scene]['df']['label'] == selected_label, 'exclude'
                                ] = new_exclude
                                
                                print(f'Toggled label {selected_label} exclude: {current_exclude} -> {new_exclude}')
                                
                                # Update display using tile slicing
                                # Account for initial padding offset in montage layout
                                y_start = row * (tile_h + padding) + padding
                                y_end = y_start + tile_h
                                x_start = col * (tile_w + padding) + padding
                                x_end = x_start + tile_w
                                
                                all_data = self.viewer.layers['all'].data
                                
                                if is_3d:
                                    tile_data = all_data[:, y_start:y_end, x_start:x_end]
                                else:
                                    tile_data = all_data[y_start:y_end, x_start:x_end]
                                
                                if new_exclude:
                                    # Label is now excluded
                                    if is_3d:
                                        self.viewer.layers['included'].data[:, y_start:y_end, x_start:x_end] = 0
                                        self.viewer.layers['excluded'].data[:, y_start:y_end, x_start:x_end] = tile_data
                                    else:
                                        self.viewer.layers['included'].data[y_start:y_end, x_start:x_end] = 0
                                        self.viewer.layers['excluded'].data[y_start:y_end, x_start:x_end] = tile_data
                                else:
                                    # Label is now included
                                    if is_3d:
                                        self.viewer.layers['included'].data[:, y_start:y_end, x_start:x_end] = tile_data
                                        self.viewer.layers['excluded'].data[:, y_start:y_end, x_start:x_end] = 0
                                    else:
                                        self.viewer.layers['included'].data[y_start:y_end, x_start:x_end] = tile_data
                                        self.viewer.layers['excluded'].data[y_start:y_end, x_start:x_end] = 0
                                
                                self.viewer.layers['included'].refresh()
                                self.viewer.layers['excluded'].refresh()
                                
                                print('Display updated using tile slicing')
                            else:
                                print(f'Tile index {tile_idx} out of range (batch has {len(self.current_batch_labels)} labels)')
                    else:
                        print('No current batch labels available')
                        
                except Exception as e:
                    print(f'ERROR in Alt-click handler: {type(e).__name__}: {e}')
                    import traceback
                    traceback.print_exc()

            if 'Shift' in event.modifiers and self.has_initialized_scene:
                print('\n=== Shift-Click (Tile-Based) Debug ===')
                print(f'Event position: {event.position}')
                
                try:
                    if self.current_threshold_measurement is None or self.current_threshold_measurement == "...":
                        print("WARNING: No threshold measurement selected. Cannot toggle positivity status.")
                        return
                    
                    scene = self.current_scene
                    if not 'positive' in self.dataset[scene]['df'].columns:
                        print("INFO: Adding 'positive' column to dataset for thresholding.")
                        self.dataset[scene]['df']['positive'] = False
                    
                    # Get click position
                    position = np.round(event.position).astype(int)
                    print(f'Position (rounded): {position}')
                    
                    # Determine which label layer to use based on viewing mode
                    viewing_mode = getattr(self, 'viewing_mode', ViewingMode.mosaic)
                    if viewing_mode == ViewingMode.slide:
                        if 'slide_labels' not in self.viewer.layers:
                            print("Slide labels layer not found")
                            return
                        labels_data = self.viewer.layers['slide_labels'].data
                    else:
                        if 'all_labels' not in self.viewer.layers:
                            print("All labels layer not found")
                            return
                        labels_data = self.viewer.layers['all_labels'].data
                    
                    # Determine if 2D or 3D
                    is_3d = labels_data.ndim == 3
                    
                    # Extract Y, X coordinates
                    if is_3d:
                        z_idx, y_idx, x_idx = position[0], position[1], position[2]
                    else:
                        y_idx, x_idx = position[0], position[1]

                    # Slide mode: direct label lookup instead of tile index lookup
                    if viewing_mode == ViewingMode.slide:
                        if is_3d:
                            clicked_label = labels_data[z_idx, y_idx, x_idx]
                        else:
                            clicked_label = labels_data[y_idx, x_idx]

                        if clicked_label == 0:
                            print('No label at clicked position (background)')
                        else:
                            df = self.dataset[scene]['df']
                            df_channel = df.loc[df['channel'] == self.current_threshold_channel]
                            if clicked_label not in df_channel['label'].values:
                                print(f'Label {clicked_label} not found in current threshold channel')
                                return

                            current_positive = df_channel.loc[df_channel['label'] == clicked_label, 'positive'].iloc[0]
                            new_positive = not current_positive

                            df.loc[(df['channel'] == self.current_threshold_channel) &
                                   (df['label'] == clicked_label), 'positive'] = new_positive

                            print(f'Toggled label {clicked_label} positive: {current_positive} -> {new_positive}')
                            self.dataset[scene]['df'] = df
                            self.update_points()
                        return
                    
                    # Check if in excluded region
                    in_excluded = x_idx >= self.excluded_translate[1]
                    if in_excluded:
                        x_idx = x_idx - int(self.excluded_translate[1])
                        print(f'Click in excluded region, adjusted x: {x_idx}')
                    
                    # Calculate which tile was clicked using grid layout
                    if hasattr(self, 'current_batch_labels') and len(self.current_batch_labels) > 0:
                        # Get actual tile dimensions (accounts for montage mode)
                        tile_h = getattr(self, 'current_tile_h', self.crop_size)
                        tile_w = getattr(self, 'current_tile_w', self.crop_size)
                        padding = 5
                        
                        print(f'Tile size: {tile_h}x{tile_w}, padding: {padding}')
                        
                        # Calculate which tile row and column
                        row = y_idx // (tile_h + padding)
                        col = x_idx // (tile_w + padding)
                        
                        print(f'Clicked tile: row={row}, col={col}')
                        
                        # Check if click is in padding
                        y_in_tile = y_idx % (tile_h + padding)
                        x_in_tile = x_idx % (tile_w + padding)
                        
                        if y_in_tile >= tile_h or x_in_tile >= tile_w:
                            print('Click in padding, ignoring')
                        else:
                            # Calculate linear index
                            tile_idx = row * self.n_cols + col
                            
                            if tile_idx < len(self.current_batch_labels):
                                selected_label = self.current_batch_labels[tile_idx]
                                print(f'Selected label from tile index {tile_idx}: {selected_label}')
                                
                                # Get DataFrame filtered to current threshold channel
                                df = self.dataset[scene]['df']
                                df_channel = df.loc[df['channel'] == self.current_threshold_channel]
                                
                                # Toggle positive status
                                current_positive = df_channel.loc[df_channel['label'] == selected_label, 'positive'].values[0]
                                new_positive = not current_positive
                                
                                # Update positive for this channel
                                df.loc[(df['channel'] == self.current_threshold_channel) & 
                                       (df['label'] == selected_label), 'positive'] = new_positive
                                
                                print(f'Toggled label {selected_label} positive: {current_positive} -> {new_positive}')
                                
                                # Update the full scene dataframe
                                self.dataset[scene]['df'] = df
                                
                                # Update points display
                                self.update_points()
                            else:
                                print(f'Tile index {tile_idx} out of range (batch has {len(self.current_batch_labels)} labels)')
                    else:
                        print('No current batch labels available')
                        
                except Exception as e:
                    print(f'ERROR in Shift-click handler: {type(e).__name__}: {e}')
                    import traceback
                    traceback.print_exc()


