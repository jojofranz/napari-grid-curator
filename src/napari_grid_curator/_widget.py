    def _load_scene(self, scene_name, batch):
        """
        Load and display a scene (or batch of scene) in napari viewer.
        """
        try:
            self._load_scene_impl(scene_name, batch)
        except Exception as e:
            print(f"\n❌ FATAL ERROR in _load_scene:")
            print(f"{type(e).__name__}: {str(e)}")
            import traceback
            traceback.print_exc()
            show_info(
                f"⚠️ Failed to load scene: {str(e)[:150]}")
    
    def _load_scene_impl(self, scene_name, batch):
        """
        Internal implementation of scene loading (wrapped in try-except by _load_scene).
        
        This is the core display method that:
        1. Applies downsampling to images if configured
        2. Filters to current batch of nuclei
        3. Partitions nuclei into included/excluded based on exclusion criteria
        4. Generates grid layouts for visualization
        
        Parameters:
            scene_name (str): Name of scene to load from dataset
            batch (int): Batch number to display (0-indexed)
            
        Side Effects:
            - Updates viewer layers: 'all', 'all_labels', 'included', 'excluded', 'points'
            - Sets self.current_scene, self.current_batch
            - Sets self.excluded_translate (offset for excluded grid)
            - Sets self.coords (grid coordinates)
            - Sets self.has_initialized_scene = True
            
        Implementation Details:
            - Uses deepcopy on images to prevent mutation
            - Applies scipy.ndimage.zoom for downsampling
            - Batch filtering based on label range [batch*size, (batch+1)*size)
            - Uses partitions_to_grid() from proc.py for grid generation
            - Excluded grid displayed with horizontal translation offset
            - Slide mode: displays full scene image with cell navigation
        """
        
        # Check viewing mode
        viewing_mode = getattr(self, 'viewing_mode', ViewingMode.mosaic)
        
        if viewing_mode == ViewingMode.slide:
            self._load_scene_slide_mode(scene_name)
            return

        if scene_name != self.current_scene:
            # Calculate batches from DataFrame (works for all three modes)
            df_scene = self.dataset[scene_name]['df']
            n_unique_labels = len(df_scene['label'].unique())
            available_batches = int(np.ceil(n_unique_labels / self.batch_size))
            available_batches = np.arange(available_batches)
            self.select_batch_widget.choices = available_batches
        self.current_batch = batch

        # Get DataFrame
        df = self.dataset[scene_name]['df']
        
        # FIX: Get unique labels first, then slice by position (not by label value!)
        # Labels are NOT sequential - they can be [8, 10, 76, 34, ...] so we need
        # to slice by array index, not filter by label value range
        unique_labels = np.sort(df['label'].unique())  # Sort for consistent ordering
        start_idx = self.current_batch * self.batch_size
        stop_idx = min((self.current_batch + 1) * self.batch_size, len(unique_labels))
        batch_labels = unique_labels[start_idx:stop_idx].tolist()
        
        # Store current batch labels for use in update_points() and other methods
        self.current_batch_labels = batch_labels
        
        # Filter DataFrame to only rows with labels in current batch
        df = df[df['label'].isin(batch_labels)]
        
        # Store current camera state to preserve view
        camera_center = None
        camera_zoom = None
        if self.has_initialized_scene:
            camera_center = self.viewer.camera.center
            camera_zoom = self.viewer.camera.zoom
        
        # Determine if we should load 3D volumes (for 3D datasets in mosaic mode)
        # Default: 3D datasets load volumes in mosaic mode for scrolling
        load_as_volume = (self.dataset_loader.is_3d() and 
                         self.dataset_mode == 'minimal' and
                         viewing_mode == ViewingMode.mosaic)
        
        # Override projection for 3D volume mode
        if load_as_volume:
            projection_mode = 'volume'
        else:
            projection_mode = getattr(self, 'z_mode', 'middle')
        
        # Load images using dataset loader (handles all three formats)
        print(f"Loading scene '{scene_name}' batch {batch} ({len(batch_labels)} cells) in {self.dataset_mode} mode (3D volume: {load_as_volume})...")
        
        try:
            if self.dataset_mode == 'minimal':
                # For minimal mode, use public API which handles both 2D (.lif) and 3D (TIFF/NIfTI/Zarr) formats
                # Pass batch_labels for efficient on-the-fly cropping (only crop requested labels)
                display_mode = self.crop_display_mode.name if hasattr(self, 'crop_display_mode') else 'overlay'
                
                # Load images
                all_images = self.dataset_loader.load_scene_images(
                    scene_name, 
                    crop_size=self.crop_size, 
                    display_mode=display_mode.lower() if hasattr(display_mode, 'lower') else display_mode,
                    projection=projection_mode,
                    overlay_segmentation=self.overlay_segmentation_boundary,
                    labels_to_load=batch_labels  # OPTIMIZATION: Only crop requested labels
                )
                # No need to filter again - loader already filtered to batch_labels
                images = {label: deepcopy(all_images[label]) for label in all_images}
                
                # Load segmentations for 3D volume mode
                if load_as_volume:
                    print(f"Loading 3D segmentations for overlay...")
                    segmentations = self.dataset_loader._crop_segmentations_from_3d_files(
                        scene_name,
                        crop_size=self.crop_size,
                        projection='volume',
                        zero_out_labels=None
                    )
                    # Filter to batch labels
                    segmentations = {label: segmentations[label] for label in batch_labels if label in segmentations}
                else:
                    segmentations = None
            else:
                # For legacy/lazy modes - load all then filter to batch
                all_images = self.dataset_loader.load_scene_images(scene_name)
                # Filter to batch labels and make a copy
                images = {label: deepcopy(all_images[label]) for label in batch_labels if label in all_images}
            
            # Apply downsampling with parallel processing
            if self.downsampling_factor > 1:
                def downsample_image(label_img_tuple):
                    label, img = label_img_tuple
                    factor = 1 / self.downsampling_factor
                    if img.ndim == 2:
                        zoom = (factor, factor)
                    elif img.ndim == 3:
                        if img.shape[-1] in (1, 2, 3, 4):
                            zoom = (factor, factor, 1)
                        elif img.shape[0] in (1, 2, 3, 4):
                            zoom = (1, factor, factor)
                        else:
                            zoom = (factor, factor, 1)
                    else:
                        zoom = tuple([factor] * img.ndim)
                    downsampled = scipy.ndimage.zoom(
                        img, 
                        zoom,
                        order=3, 
                        mode='nearest'
                    )
                    return label, downsampled
                
                # Parallel downsampling
                downsampled_images = {}
                with ThreadPoolExecutor(max_workers=4) as executor:
                    futures = {executor.submit(downsample_image, item): item[0] for item in images.items()}
                    for future in progress(as_completed(futures), total=len(futures), desc="Downsampling images"):
                        label, downsampled_img = future.result()
                        downsampled_images[label] = downsampled_img
                images = downsampled_images
            else:
                # No downsampling, just filter
                images = {label: img for label, img in images.items() if label in df['label'].values}

            included_labels, excluded_labels = partition_images(df)
            
            # Get unique labels for grid
            # After dataset loading, 'label' is always the correct column (instance_label was renamed to label for relabel mode)
            labels = df['label'].drop_duplicates().values.astype(int)
            images = prepare_images_for_grid(images, labels)
            
            # Store actual tile dimensions from loaded images (accounts for montage mode)
            # In montage mode, each image is already arranged as channel grid, so shape reflects that
            first_label = labels[0]
            if first_label in images:
                first_img = images[first_label]
                if first_img.ndim >= 2:
                    self.current_tile_h = first_img.shape[0]
                    self.current_tile_w = first_img.shape[1]
                else:
                    # Fallback to crop_size
                    self.current_tile_h = self.crop_size
                    self.current_tile_w = self.crop_size
            else:
                # Fallback to crop_size if no images
                self.current_tile_h = self.crop_size
                self.current_tile_w = self.crop_size
            
            print(f'Actual tile dimensions: {self.current_tile_h} x {self.current_tile_w}')
            print(f'labels for grid: {labels}')
            
            # Create grid based on dimensionality
            if load_as_volume:
                # 3D volume mode - create 3D montage with segmentation overlay
                print(f"Creating 3D montage with {len(images)} volumes and {len(segmentations)} segmentation masks...")
                (all_images_grid, all_labels_grid, coords, 
                 included_images, excluded_images,
                 included_labels_grid, excluded_labels_grid) = partitions_to_grid_3d(
                    images, segmentations, labels, included_labels, excluded_labels, cols=self.n_cols
                )
            else:
                # 2D mode - use standard 2D montage
                all_images_grid, all_labels, coords, included_images, excluded_images = partitions_to_grid(
                    images, labels, included_labels, excluded_labels, cols=self.n_cols
                )
                all_labels_grid = all_labels
                included_labels_grid = None
                excluded_labels_grid = None
            
            # Calculate translation for excluded grid
            if load_as_volume:
                # For 3D, get Y dimension (axis 1)
                excluded_translate = (0, included_images.shape[1] + (included_images.shape[1]/self.n_cols))
            else:
                # For 2D
                excluded_translate = (0, included_images.shape[1] + (included_images.shape[1]/self.n_cols))
            self.excluded_translate = excluded_translate

            self.current_scene = scene_name

            # Create image layers
            self.get_create_layer(self.viewer, all_images_grid, 'all', visible=False, translate=[0, 0], layer_type='image')
            self.get_create_layer(self.viewer, included_images, 'included', visible=True, translate=[0, 0], layer_type='image')
            self.get_create_layer(self.viewer, excluded_images, 'excluded', visible=True, translate=excluded_translate, layer_type='image')
            
            # Create label layers (above images, below points)
            if load_as_volume:
                # 3D mode: create separate label layers for included/excluded with proper overlay
                self.get_create_layer(self.viewer, all_labels_grid, 'all_labels', visible=False, translate=[0, 0], layer_type='labels')
                self.get_create_layer(self.viewer, included_labels_grid, 'included_labels', visible=True, translate=[0, 0], layer_type='labels')
                self.get_create_layer(self.viewer, excluded_labels_grid, 'excluded_labels', visible=True, translate=excluded_translate, layer_type='labels')
                
                # Make labels semi-transparent
                if 'included_labels' in self.viewer.layers:
                    self.viewer.layers['included_labels'].opacity = 0.5
                if 'excluded_labels' in self.viewer.layers:
                    self.viewer.layers['excluded_labels'].opacity = 0.5
            else:
                # 2D mode: single labels layer
                self.get_create_layer(self.viewer, all_labels_grid, 'all_labels', visible=False, translate=[0, 0], layer_type='labels')
            
            # Create points layer (on top)
            self.coords = coords
            all_coords = np.vstack([coords, coords + excluded_translate])
            print(f"Creating points layer with {len(all_coords)} points...")
            self.get_create_layer(self.viewer, all_coords, 'points', visible=True, translate=[0, 0], layer_type='points')
            
            print(f"Updating points for scene '{scene_name}'...")
            self.update_points()
            print(f"✓ Points updated successfully")
            self.has_initialized_scene = True
            
            print(f"Ensuring proper layer ordering...")
            # Ensure proper layer ordering: images < labels < points
            self._ensure_layer_ordering()
            print(f"✓ Layer ordering established")
            
            print(f"Restoring camera state...")
            # Restore camera state if it was preserved
            if camera_center is not None and camera_zoom is not None:
                self.viewer.camera.center = camera_center
                self.viewer.camera.zoom = camera_zoom
            else:
                # Force viewer refresh only on first load
                self.viewer.reset_view()
            
            print(f"✓ Scene '{scene_name}' loaded successfully!\n")
        
        except (FileNotFoundError, RuntimeError) as e:
            error_message = str(e)
            print(f"\n❌ FileNotFoundError/RuntimeError loading scene '{scene_name}':")
            print(f"{error_message}")
            import traceback
            traceback.print_exc()
            show_info(
                f"⚠️ Error loading scene: {error_message[:200]}")
            return
        except Exception as e:
            print(f"\n❌ UNEXPECTED ERROR loading scene '{scene_name}':")
            print(f"{type(e).__name__}: {str(e)}")
            import traceback
            traceback.print_exc()
            
            error_message = (
                f"Unexpected error loading scene '{scene_name}':\n{str(e)}\n\n"
                "This might be a bug. Please report with the error details above."
            )
            show_info(
                f"⚠️ Unexpected error: {str(e)[:100]}...")
            return
    
    def _ensure_layer_ordering(self):
        """
        Ensure proper layer ordering: images < labels < points.
        
        Layer ordering in napari determines rendering order (bottom to top).
        We want: background images, then segmentation labels, then annotation points.
        """
        # Define desired ordering
        desired_order = [
            'all', 'included', 'excluded',  # Image layers (bottom)
            'all_labels', 'included_labels', 'excluded_labels',  # Label layers (middle)
            'slide_image', 'slide_labels',  # Slide mode layers
            'points'  # Points layer (top)
        ]
        
        # Move layers to correct positions (iterate forward, move each to end)
        # This results in the desired_order being preserved
        for layer_name in desired_order:
            if layer_name in self.viewer.layers:
                layer = self.viewer.layers[layer_name]
                current_idx = self.viewer.layers.index(layer)
                target_idx = len(self.viewer.layers) - 1
                
                # Only move if needed
                if current_idx != target_idx:
                    self.viewer.layers.move(current_idx, target_idx)
    
    def _load_scene_slide_mode(self, scene_name):
        """
        Load scene in slide mode - displays full image with cell navigation.
        
        In slide mode:
        - Shows the full microscopy image
        - Overlays segmentation labels
        - Allows clicking through individual cells
        - Supports include/exclude toggling via clicks
        
        Parameters:
            scene_name (str): Name of scene to load
        """
        from aicsimageio import AICSImage
        from microfilm import colorify
        
        self.current_scene = scene_name
        self.current_batch = 0
        
        # Get DataFrame for this scene
        df = self.dataset[scene_name]['df']
        
        # Filter to unique cells only (one row per cell, not per channel)
        # Group by label and take first row for each cell
        df_unique = df.groupby('label').first().reset_index()
        
        # Sanity check: verify bbox coordinates are consistent across channels
        # Generally, different bboxes for the same cell are bad/indicate an error in preprocessing
        # Sometimes different bboxes for the same cell are acceptable, e.g. in our case of channels: DAPI_inside, DAPI_dilated, ...
        show_n_warnings = 3
        n_warnings = 0
        bbox_cols = ['bbox-0', 'bbox-1', 'bbox-2', 'bbox-3']
        for label in df['label'].unique():
            cell_rows = df[df['label'] == label]
            if n_warnings < show_n_warnings:
                if len(cell_rows) > 1:
                    # Check if all bbox coordinates are identical
                    for col in bbox_cols:
                        if cell_rows[col].nunique() > 1:
                            print(f"WARNING: Cell {label} has misaligned bbox coordinates across channels!")
                            print(f"  {col} values: {cell_rows[col].unique()}")
                            print(f"  channel values: {cell_rows['channel'].unique()}")
                            n_warnings += 1
                            if n_warnings >= show_n_warnings:
                                print("... (further warnings suppressed)")
                                break

        # Store cells for navigation (one entry per cell)
        self.slide_mode_cells = df_unique.to_dict('records')
        self.slide_mode_cell_index = 0
        
        # Update navigation controls
        self.current_cell_label.setText(f"Cell: 1/{len(self.slide_mode_cells)}")
        self.goto_cell_spinbox.max = len(self.slide_mode_cells)
        self.goto_cell_spinbox.value = 1
        
        # Load full image
        if self.dataset_mode == 'minimal':
            is_3d_dataset = self.dataset_loader.is_3d()
            
            if is_3d_dataset and hasattr(self.dataset_loader, '_is_3d_file_based') and self.dataset_loader._is_3d_file_based:
                # 3D file-based format (TIFF/NIfTI/Zarr) - load directly
                img_path = os.path.join(self.dataset_loader.base_dir, self.dataset_loader.metadata['image_file'])
                image_filetype = self.dataset_loader.metadata.get('image_filetype', 'tiff')
                image_dims = self.dataset_loader.metadata.get('image_dims', 'ZYX')
                
                print(f"Loading 3D image for slide mode from {img_path}...")
                full_image = self.dataset_loader._load_3d_file(img_path, image_filetype, image_dims, as_int=False)
                print(f"Loaded 3D image with shape {full_image.shape}")
                
                # Ensure (C, Z, Y, X) format
                if len(full_image.shape) == 3:
                    full_image = full_image[np.newaxis, ...]  # (Z, Y, X) -> (1, Z, Y, X)
            else:
                #  2D .lif-based format
                lif_path = os.path.join(self.dataset_loader.base_dir, self.dataset[scene_name]['_lif_file'])
                lif = AICSImage(lif_path)
                scene_name_in_lif = self.dataset[scene_name]['_scene_name']
                lif.set_scene(scene_name_in_lif)
                full_image = lif.data.squeeze()  # (C, Y, X) or (C, Z, Y, X)
            
            # Convert to RGB
            is_3d = len(full_image.shape) == 4
            
            cmaps = self.dataset_loader.get_channel_cmaps()
            if cmaps is None:
                n_channels = full_image.shape[0]
                cmaps = ['pure_blue', 'pure_green', 'pure_red', 'pure_cyan', 'pure_magenta'][:n_channels]
            
            if is_3d:
                # 3D: (C, Z, Y, X) -> (Z, Y, X, 4) with RGBA
                n_channels, Z, Y, X = full_image.shape
                rgb_image = np.zeros((Z, Y, X, 4), dtype=np.float32)
                
                # Process each Z slice
                print(f"Converting 3D image to RGB (shape: {full_image.shape})...")
                for z_idx in range(Z):
                    slice_2d = full_image[:, z_idx, :, :]  # (C, Y, X)
                    
                    limits = [[np.percentile(slice_2d[c], 0), np.percentile(slice_2d[c], 100)] 
                             for c in range(n_channels)]
                    
                    try:
                        rgb_slice, _, _, _ = colorify.multichannel_to_rgb(
                            slice_2d,
                            cmaps[:n_channels],
                            rescale_type='limits',
                            limits=limits,
                            proj_type='sum'
                        )
                        rgb_image[z_idx] = rgb_slice
                    except Exception as e:
                        if z_idx == 0:  # Only print error once
                            print(f"Error converting to RGB: {e}, using fallback")
                        # Fallback
                        fallback = slice_2d[:min(3, n_channels)].transpose(1, 2, 0)
                        fallback = (fallback - fallback.min()) / (fallback.max() - fallback.min() + 1e-8)
                        if fallback.shape[-1] == 1:
                            fallback = np.repeat(fallback, 3, axis=-1)
                        elif fallback.shape[-1] == 2:
                            fallback = np.pad(fallback, ((0,0), (0,0), (0,1)), constant_values=0)
                        alpha = np.ones((Y, X, 1), dtype=np.float32)
                        rgb_image[z_idx] = np.concatenate([fallback, alpha], axis=-1)
            else:
                # 2D: (C, Y, X) -> (Y, X, 4)
                limits = [[np.percentile(full_image[c], 0), np.percentile(full_image[c], 100)] 
                         for c in range(full_image.shape[0])]
                
                try:
                    rgb_image, _, _, _ = colorify.multichannel_to_rgb(
                        full_image,
                        cmaps[:full_image.shape[0]],
                        rescale_type='limits',
                        limits=limits,
                        proj_type='sum'
                    )
                except Exception as e:
                    print(f"Error converting to RGB: {e}, using fallback")
                    # Fallback: use first 3 channels as RGB
                    rgb_image = full_image[:3].transpose(1, 2, 0)
                    rgb_image = (rgb_image - rgb_image.min()) / (rgb_image.max() - rgb_image.min() + 1e-8)
            
            # Load labels
            if self.dataset[scene_name]['_labels'] is None:
                label_path = os.path.join(self.dataset_loader.base_dir, self.dataset[scene_name]['_label_file'])
                if self.dataset_loader.metadata['save_format'] == 'zarr':
                    import zarr
                    labels = zarr.load(label_path)
                else:
                    labels = np.load(label_path)
                self.dataset[scene_name]['_labels'] = labels
            else:
                labels = self.dataset[scene_name]['_labels']
        else:
            # For legacy/lazy modes, we don't have the full image easily
            # Show a message or fall back to mosaic mode
            print("Slide mode requires minimal format for full image access")
            self.viewing_mode = ViewingMode.mosaic
            self.viewing_mode_widget.value = 'mosaic'
            self._load_scene(scene_name, 0)
            return
        
        # Clear existing layers
        layers_to_remove = ['all', 'all_labels', 'included', 'excluded', 'points', 'slide_image', 'slide_labels']
        for layer_name in layers_to_remove:
            if layer_name in self.viewer.layers:
                self.viewer.layers.remove(layer_name)
        
        # Add layers
        self.get_create_layer(self.viewer, rgb_image, 'slide_image', visible=True, translate=[0, 0], layer_type='image')
        self.get_create_layer(self.viewer, labels, 'slide_labels', visible=True, translate=[0, 0], layer_type='labels')
        
        # Make labels semi-transparent for overlay effect
        if 'slide_labels' in self.viewer.layers:
            self.viewer.layers['slide_labels'].opacity = 0.3
        
        self.has_initialized_scene = True
        
        # Add cell center points with proper styling (colors, text labels)
        # This will call update_points() which handles styling based on threshold
        self.update_points()
        
        # Ensure proper layer ordering: image < labels < points
        self._ensure_layer_ordering()
        
        # Center on first cell
        self._update_slide_mode_display()


    def change_downsampling(self, value):
        """
        Update downsampling factor and reload current scene.
        
        Higher downsampling values reduce image resolution for faster
        rendering at the cost of visual detail.
        
        Parameters:
            value (int): New downsampling factor (1-4)
        """
        value = int(value)
        self.downsampling_factor = value
        self.load_scene(self.current_scene)
    
    def change_crop_size(self, value):
        """
        Update crop size for minimal mode and reload current batch.
        
        Parameters:
            value (int): New crop size in pixels (30-120)
        """
        value = int(value)
        self.crop_size = value
        if self.dataset_mode == 'minimal' and self.current_scene is not None:
            self.load_batch(self.current_batch)


