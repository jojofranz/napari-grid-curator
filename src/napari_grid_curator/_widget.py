def create_channels_enum(channel_names):
    """
    Dynamically create a Channels enum from channel names found in dataset.
    
    This makes the plugin data-agnostic - it works with any channel names
    without requiring hardcoded enums.
    
    Parameters:
        channel_names (list[str]): List of channel names from dataset
        
    Returns:
        Enum: Dynamically created Channels enum with members for each channel
        
    Example:
        >>> create_channels_enum(['DAPI_inside', 'RBPMS_inside', 'Islet1_inside'])
        <enum 'Channels'> with members: DAPI_inside, RBPMS_inside, Islet1_inside
    """
    # Create enum dynamically using functional API
    # Use channel name as both the enum member name and its value
    channel_dict = {name: name for name in channel_names}
    return Enum('Channels', channel_dict)

