    def update_exclusion_metrics(self, metrics):
        """
        Update active exclusion metrics and recalculate exclusion status.
        
        Combines multiple exclusion criteria using OR logic: a nucleus is
        excluded if it fails ANY of the selected metrics.
        
        Parameters:
            metrics (list[ExclusionMetrics]): New list of metrics to apply
            
        Side Effects:
            - Updates 'exclude' column in all scene DataFrames
            - Reloads current batch to show updated exclusions
            
        Implementation:
            - Other metrics read from 'exclude (metric_name)' DataFrame columns
        """
        self.exclusion_metrics = metrics
        self.exclusion_metrics_names = [m.name for m in metrics]

        for scene in self.scene_choices:
            if not scene == "...":
                df = self.dataset[scene]['df']
                exclude = np.zeros(len(df), dtype=bool)
                for metric in self.exclusion_metrics_names:
                    metric = f'exclude ({metric})'
                    exclude |= df[metric].values

                df['exclude'] = exclude
                self.dataset[scene]['df'] = df
        
        # Update display without full reload
        if self.has_initialized_scene and self.current_scene is not None:
            self.update_display_layers()

    def update_display_layers(self):
        """
        Update the display layers (included/excluded/points) without full scene reload.
        Used when only exclusion status changes, not the underlying images.
        Uses tile-based extraction for consistency with click handlers.
        """
        if self.current_scene is None:
            return
        
        # Get current batch data
        df = self.dataset[self.current_scene]['df']
        
        # Filter by current batch labels
        if hasattr(self, 'current_batch_labels'):
            batch_labels = self.current_batch_labels
            df = df[df['label'].isin(batch_labels)]
        else:
            # Fallback: compute batch labels if not stored
            unique_labels = np.sort(df['label'].unique())
            start_idx = self.current_batch * self.batch_size
            stop_idx = min((self.current_batch + 1) * self.batch_size, len(unique_labels))
            batch_labels = unique_labels[start_idx:stop_idx].tolist()
            df = df[df['label'].isin(batch_labels)]
        
        # Get current images from viewer (already loaded)
        if 'all' not in self.viewer.layers:
            return
        
        all_images_grid = self.viewer.layers['all'].data
        is_3d = all_images_grid.ndim == 4 or (all_images_grid.ndim == 3 and self.dataset_loader.is_3d())
        
        # Recalculate partitions
        included_labels, excluded_labels = partition_images(df)
        labels = df['label'].drop_duplicates().values.astype(int)
        
        # Use tile-based extraction instead of label bounding boxes
        # This works for both 2D and 3D, and avoids the pixel-level label issue
        included_images = all_images_grid.copy()
        excluded_images = all_images_grid.copy()
        
        # Get actual tile size from stored dimensions (set during scene loading)
        # This correctly handles montage mode where tiles are larger
        tile_h = getattr(self, 'current_tile_h', self.crop_size)
        tile_w = getattr(self, 'current_tile_w', self.crop_size)
        padding = 5
        
        print(f'Using tile dimensions for masking: {tile_h} x {tile_w}')
        
        # Zero out tiles based on inclusion/exclusion
        for idx, label in enumerate(batch_labels):
            row = idx // self.n_cols
            col = idx % self.n_cols
            
            # Account for initial padding offset in montage layout
            y_start = row * (tile_h + padding) + padding
            y_end = y_start + tile_h
            x_start = col * (tile_w + padding) + padding
            x_end = x_start + tile_w
            
            # Zero out the tile in the appropriate grid
            if label in excluded_labels:
                # This label is excluded, so zero it in included grid
                if is_3d:
                    included_images[:, y_start:y_end, x_start:x_end] = 0
                else:
                    included_images[y_start:y_end, x_start:x_end] = 0
            elif label in included_labels:
                # This label is included, so zero it in excluded grid
                if is_3d:
                    excluded_images[:, y_start:y_end, x_start:x_end] = 0
                else:
                    excluded_images[y_start:y_end, x_start:x_end] = 0
        
        # Update layers
        self.viewer.layers['included'].data = included_images
        self.viewer.layers['excluded'].data = excluded_images
        
        # Force refresh
        self.viewer.layers['included'].refresh()
        self.viewer.layers['excluded'].refresh()
        
        # Update points (coords don't change, just colors/text)
        self.update_points()
    
