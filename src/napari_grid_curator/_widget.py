    def _browse_lif_file(self):
        """Browse for .lif file."""
        from qtpy.QtWidgets import QFileDialog
        file_path, _ = QFileDialog.getOpenFileName(self, "Select .lif file", "", "LIF files (*.lif)")
        if file_path:
            self.lif_path_edit.setText(file_path)
    
    def _browse_labels_dir(self):
        """Browse for labels directory."""
        from qtpy.QtWidgets import QFileDialog
        dir_path = QFileDialog.getExistingDirectory(self, "Select labels directory")
        if dir_path:
            self.labels_dir_edit.setText(dir_path)
    
    def _apply_path_fixes(self, dialog):
        """Apply the path fixes."""
        if self.dataset_mode == 'minimal':
            lif_path = self.lif_path_edit.text()
            labels_dir = self.labels_dir_edit.text()
            
            success = self.dataset_loader.fix_paths(
                lif_path=lif_path if lif_path else None,
                labels_dir=labels_dir if labels_dir else None
            )
            
            if success:
                show_info("Paths fixed successfully!")
                self.fix_paths_btn.setVisible(False)
                dialog.accept()
            else:
                show_info("Some paths could not be fixed. Check the console for details.")
        
        dialog.accept()


