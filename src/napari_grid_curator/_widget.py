def make_spinbox_enter_only(spinbox_widget, callback):
    """
    Configure a magicgui SpinBox to only trigger callback on Enter key press.
    
    Disconnects the default changed signal and connects to editingFinished instead.
    Also disables keyboard tracking so value only updates when editing is done.
    
    Parameters:
        spinbox_widget: magicgui SpinBox widget
        callback: Function to call when Enter is pressed
    """
    # Get the underlying QSpinBox widget
    qspinbox = spinbox_widget._widget._qwidget
    
    # Disable keyboard tracking (don't update while typing)
    qspinbox.setKeyboardTracking(False)
    
    # Connect editingFinished signal (fires on Enter or focus loss)
    qspinbox.editingFinished.connect(lambda: callback(spinbox_widget.value))


class SliderSpinBox(QWidget):
    """
    Combined Slider + SpinBox widget for value input.
    
    Provides both a slider for quick adjustments and a spinbox for 
    precise value entry. Values are synchronized between both controls.
    
    The callback is triggered:
    - On slider release (not during drag)
    - On spinbox Enter key or focus loss
    
    Attributes:
        slider: QSlider for quick adjustment
        spinbox: QSpinBox for precise entry
        callback: Function to call when value changes
    """
    
    def __init__(self, value=0, min_val=0, max_val=100, step=1, callback=None, parent=None):
        super().__init__(parent)
        
        self.callback = callback
        self._value = value
        
        layout = QHBoxLayout()
        layout.setContentsMargins(0, 0, 0, 0)
        
        # Create slider
        from qtpy.QtWidgets import QSlider, QSpinBox
        self.slider = QSlider(Qt.Horizontal)
        self.slider.setMinimum(min_val)
        self.slider.setMaximum(max_val)
        self.slider.setSingleStep(step)
        self.slider.setValue(value)
        self.slider.setTracking(False)  # Only emit on release
        
        # Create spinbox
        self.spinbox = QSpinBox()
        self.spinbox.setMinimum(min_val)
        self.spinbox.setMaximum(max_val)
        self.spinbox.setSingleStep(step)
        self.spinbox.setValue(value)
        self.spinbox.setKeyboardTracking(False)
        
        # Sync slider -> spinbox
        self.slider.valueChanged.connect(self._slider_changed)
        
        # Sync spinbox -> slider (on enter/focus loss)
        self.spinbox.editingFinished.connect(self._spinbox_finished)
        
        layout.addWidget(self.slider, stretch=3)
        layout.addWidget(self.spinbox, stretch=1)
        self.setLayout(layout)
    
    def _slider_changed(self, value):
        """Handle slider value change (only fires on release)."""
        self._value = value
        self.spinbox.blockSignals(True)
        self.spinbox.setValue(value)
        self.spinbox.blockSignals(False)
        if self.callback:
            self.callback(value)
    
    def _spinbox_finished(self):
        """Handle spinbox editing finished."""
        value = self.spinbox.value()
        if value != self._value:
            self._value = value
            self.slider.blockSignals(True)
            self.slider.setValue(value)
            self.slider.blockSignals(False)
            if self.callback:
                self.callback(value)
    
    @property
    def value(self):
        return self._value
    
    @value.setter
    def value(self, val):
        self._value = val
        self.slider.blockSignals(True)
        self.spinbox.blockSignals(True)
        self.slider.setValue(val)
        self.spinbox.setValue(val)
        self.slider.blockSignals(False)
        self.spinbox.blockSignals(False)
    
    def setMaximum(self, val):
        """Set maximum value for both slider and spinbox."""
        self.slider.setMaximum(val)
        self.spinbox.setMaximum(val)
    
    def setMinimum(self, val):
        """Set minimum value for both slider and spinbox."""
        self.slider.setMinimum(val)
        self.spinbox.setMinimum(val)


