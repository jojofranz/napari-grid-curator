        # Create histogram with colored regions
        bins = 200
        n, bin_edges, patches = self.graphics_widget.axes.hist(for_hist, bins=bins, edgecolor='none')
        
        # Color patches based on threshold (using customizable colors)
        for i, (patch, left_edge) in enumerate(zip(patches, bin_edges[:-1])):
            if left_edge < threshold:
                patch.set_facecolor(negative_color_mpl)
                patch.set_alpha(0.7)
            else:
                patch.set_facecolor(positive_color_mpl)
                patch.set_alpha(0.7)
        
        # Add vertical line at threshold
        self.graphics_widget.axes.axvline(x=threshold, color='black', linestyle='--', linewidth=2, label=f'Threshold: {threshold}')
        self.graphics_widget.axes.legend(loc='upper right')
        
        # Update canvas
        self.graphics_widget.draw()


